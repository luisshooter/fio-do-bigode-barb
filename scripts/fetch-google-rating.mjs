// Refreshes src/data/reviews.ts with the shop's current Google rating and
// review count. Run with: pnpm fetch:reviews (reads GOOGLE_PLACES_API_KEY
// and GOOGLE_PLACE_ID from .env — that key never ships to the browser,
// this script only runs locally/at build time on the developer's machine).
//
// The three quoted reviews below are hand-curated from real, named Google
// reviews (Places API does not reliably return review text for this
// place, only rating/count) — update CURATED_REVIEWS by hand if you want
// to refresh which quotes are featured; this script only refreshes the
// rating and review count automatically.

import { writeFile } from 'node:fs/promises'

const API_KEY = process.env.GOOGLE_PLACES_API_KEY
const PLACE_ID = process.env.GOOGLE_PLACE_ID

if (!API_KEY || !PLACE_ID) {
  console.error('Missing GOOGLE_PLACES_API_KEY or GOOGLE_PLACE_ID in .env')
  process.exit(1)
}

const CURATED_REVIEWS = [
  {
    author: 'Juliano Marcante',
    meta: 'Local Guide · 36 avaliações',
    quote: 'Ambiente agradável, ótimo atendimento, excelente localização, profissionais competentes. Recomendo.',
  },
  {
    author: 'Wilson Schiochet',
    meta: 'Local Guide · 43 avaliações',
    quote: 'Excelentes profissionais, espaço aconchegante, com boas músicas e bate papo descontraído.',
  },
  {
    author: 'Victor Terra',
    meta: 'Local Guide · 323 avaliações',
    quote: 'Excelente atendimento, ótimo profissional e preço justo. Recomendo.',
  },
]

const response = await fetch(`https://places.googleapis.com/v1/places/${PLACE_ID}`, {
  headers: {
    'X-Goog-Api-Key': API_KEY,
    'X-Goog-FieldMask': 'rating,userRatingCount,googleMapsUri',
  },
})

if (!response.ok) {
  console.error(`Places API request failed: ${response.status} ${await response.text()}`)
  process.exit(1)
}

const place = await response.json()

const fileContent = `// Generated by scripts/fetch-google-rating.mjs — run \`pnpm fetch:reviews\`
// to refresh the rating/review count from Google. Do not hand-edit the
// rating/reviewCount/googleMapsUri fields; edit CURATED_REVIEWS in the
// script instead, then re-run it.

export type CuratedReview = {
  author: string
  meta: string
  quote: string
}

export const GOOGLE_RATING = {
  rating: ${JSON.stringify(place.rating)},
  reviewCount: ${JSON.stringify(place.userRatingCount)},
  googleMapsUri: ${JSON.stringify(place.googleMapsUri)},
}

export const CURATED_REVIEWS: CuratedReview[] = ${JSON.stringify(CURATED_REVIEWS, null, 2)}
`

await writeFile(new URL('../src/data/reviews.ts', import.meta.url), fileContent)

console.log(`Updated src/data/reviews.ts — ${place.rating}★ (${place.userRatingCount} avaliações)`)
